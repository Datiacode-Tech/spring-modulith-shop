CREATE TABLE products (
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku   VARCHAR(50)    NOT NULL UNIQUE,
    name  VARCHAR(255)   NOT NULL,
    price NUMERIC(10, 2) NOT NULL,
    stock INTEGER        NOT NULL CHECK (stock >= 0)
);

